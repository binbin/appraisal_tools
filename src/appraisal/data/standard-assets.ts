export function getAssetsForCategory(
  category: SpecialtyCategory,
  appendix?: "A" | "B" | "C",
): StandardAsset[] {
  return STANDARD_ASSETS.filter((asset) => {
    if (!asset.categories.includes(category)) {
      return false;
    }
    if (appendix && asset.appendix !== appendix) {
      return false;
    }
    return true;
  });
}

export function listAllAssetIds(): string[] {
  return STANDARD_ASSETS.map((asset) => asset.id);
}
